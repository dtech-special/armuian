package dev.armuian.container

/**
 * Скрипты гостевой сессии. Генерируются приложением из проверенных путей и выполняются с root.
 *
 * Что делает сессия (и чего НЕ делает):
 *  - создаёт собственный mount namespace (`unshare -m ...`);
 *  - ДО любых монтирований добивается, чтобы монтирования namespace были private/slave. На Android корень `/`
 *    смонтирован как MS_SHARED, и без этого bind-монтирования «утекли» бы в хост (поэтому при неудаче — отказ);
 *  - внутри namespace монтирует /apex и /linkerconfig хоста (чтобы заработал linker) и /proc в гостевой rootfs;
 *  - проверяет, что эти монтирования НЕ видны в mount namespace хоста (/proc/1/mountinfo);
 *  - запускает в chroot ОДИН проверочный процесс гостя (`toybox sleep`).
 *  - НЕ запускает Android init и службы, не трогает SELinux, свойства и системные каталоги хоста.
 *
 * В шаблонах символ § заменяется на $ (чтобы не конфликтовать с шаблонами Kotlin).
 * Строки журнала имеют формат `[armuian] step|warn|error|mount: ...` — их разбирает [GuestLogParser].
 */
object GuestScripts {
    private val SAFE = Regex("^[A-Za-z0-9_./-]+$")
    private val FLAGS = Regex("^(-[a-z])( -[a-z])*$")

    private fun q(path: String): String {
        require(SAFE.matches(path)) { "Unsafe path for script: $path" }
        return "'$path'"
    }

    private fun fill(t: String, rootfs: String, runDir: String) =
        t.replace("@ROOT@", q(rootfs)).replace("@RUN@", q(runDir)).replace('§', '$')

    fun start(rootfs: String, runDir: String, unshareFlags: String, mode: String): String {
        require(FLAGS.matches(unshareFlags)) { "Bad unshare flags: $unshareFlags" }
        require(SAFE.matches(mode))
        return fill(START, rootfs, runDir).replace("@FLAGS@", unshareFlags).replace("@MODE@", mode)
    }

    /** Скрипт, выполняемый ВНУТРИ нового namespace. Запускается из start.sh, напрямую не вызывается. */
    fun enter(rootfs: String, runDir: String) = fill(ENTER, rootfs, runDir)
    fun stop(rootfs: String, runDir: String) = fill(STOP, rootfs, runDir)
    fun status(rootfs: String, runDir: String) = fill(STATUS, rootfs, runDir)

    private val START = """
#!/system/bin/sh
# Generated by ArmUian. Do not edit.
ROOT=@ROOT@
RUN=@RUN@
LOG="§RUN/guest.log"

# Single-instance guard: never start a second guest for the same rootfs.
OLD=§(cat "§RUN/guest.pid" 2>/dev/null)
if [ -n "§OLD" ] && [ -d "/proc/§OLD" ]; then
  OR=§(readlink -f "/proc/§OLD/root" 2>/dev/null)
  CR=§(readlink -f "§ROOT")
  if [ "§OR" = "§CR" ]; then
    echo "[armuian] error: guest is already running (pid §OLD), not starting a second one" >> "§LOG"
    exit 0
  fi
fi

: > "§LOG"
echo "[armuian] step: start mode=@MODE@ uid=§(id -u) selinux=§(getenforce 2>/dev/null)" >> "§LOG"
echo §§ > "§RUN/guest.pid"
date +%s > "§RUN/guest.started"
exec unshare @FLAGS@ -- /system/bin/sh "§RUN/enter.sh" "§ROOT" >> "§LOG" 2>&1
""".trimStart()

    private val ENTER = """
#!/system/bin/sh
# Generated by ArmUian. Runs INSIDE the new mount namespace.
R="§1"
say()  { echo "[armuian] step: §*"; }
warn() { echo "[armuian] warn: §*"; }
fail() { echo "[armuian] error: §*"; }

# Mount propagation: Android keeps / as MS_SHARED. `shared:N` in mountinfo means a mount is still a peer of the host's.
is_private() { [ -r /proc/self/mountinfo ] && ! grep -q ' shared:' /proc/self/mountinfo; }

# try_private DESCRIPTION COMMAND...   -> runs the command, logs its REAL output, then verifies the result via mountinfo.
try_private() {
  desc="§1"; shift
  say "propagation: trying §desc"
  out=§("§@" 2>&1); rc=§?
  if [ -n "§out" ]; then echo "[armuian] mount: §out"; fi
  if [ §rc -ne 0 ]; then warn "§desc failed (rc=§rc)"; return 1; fi
  if is_private; then say "propagation: private/slave verified via §desc"; return 0; fi
  warn "§desc returned 0 but shared mounts remain"; return 1
}

if is_private; then
  say "propagation: already private/slave, nothing to change"
else
  ok=1
  # util-linux / busybox syntax. toybox (Android) does NOT know --make-* and then treats "/" as a lone argument,
  # looking it up in /etc/fstab ("bad /etc/fstab") — that is exactly the failure seen on Android 16.
  if [ §ok -ne 0 ]; then try_private "mount --make-rprivate /" mount --make-rprivate / && ok=0; fi
  # toybox syntax: propagation as -o option, explicit DEVICE so that no fstab lookup happens.
  if [ §ok -ne 0 ]; then try_private "mount -o rprivate none /" mount -o rprivate none / && ok=0; fi
  # busybox from a root manager, if present.
  for bb in /data/adb/ksu/bin/busybox /data/adb/magisk/busybox /system/xbin/busybox /system/bin/busybox; do
    if [ §ok -ne 0 ] && [ -x "§bb" ]; then try_private "§bb mount --make-rprivate /" "§bb" mount --make-rprivate / && ok=0; fi
  done
  if [ §ok -ne 0 ]; then
    fail "cannot make mounts private: / is MS_SHARED on Android and no available mount implementation could change it. Aborting BEFORE any bind mount, host is untouched"
    exit 21
  fi
fi

if [ ! -e "§R/system/bin/toybox" ]; then fail "guest toybox is missing in §R"; exit 20; fi

say "prepare: creating mount points in the guest rootfs"
mkdir -p "§R/apex" "§R/linkerconfig" "§R/proc" || { fail "mkdir failed in §R"; exit 22; }

mnt() {  # mnt DESCRIPTION CMD...
  desc="§1"; shift
  say "mount: §desc"
  out=§("§@" 2>&1); rc=§?
  if [ -n "§out" ]; then echo "[armuian] mount: §out"; fi
  if [ §rc -ne 0 ]; then fail "§desc failed (rc=§rc)"; return 1; fi
  return 0
}

mnt "rbind /apex -> §R/apex" mount -o rbind /apex "§R/apex" || exit 23
mnt "rbind /linkerconfig -> §R/linkerconfig" mount -o rbind /linkerconfig "§R/linkerconfig" || exit 24
mnt "proc -> §R/proc" mount -t proc proc "§R/proc" || exit 25

# Isolation check: init's mountinfo is the HOST namespace. Our binds must not be visible there.
if grep -q " §R/apex " /proc/1/mountinfo 2>/dev/null; then
  fail "isolation broken: bind mounts are visible in the host mount namespace"
  exit 26
fi
say "isolation: verified, mounts are not visible in the host mount namespace"

say "exec: chroot §R toybox sleep (guest probe process; no Android init, no services)"
exec chroot "§R" /system/bin/toybox sleep 2147483647
""".trimStart()

    private val STOP = """
#!/system/bin/sh
ROOT=@ROOT@
RUN=@RUN@
CANON=§(readlink -f "§ROOT")
PID=§(cat "§RUN/guest.pid" 2>/dev/null)
if [ -z "§PID" ]; then
  echo "stopped=nopid"
  echo "leaked_mounts=§(grep -c " §CANON/" /proc/self/mountinfo 2>/dev/null)"
  exit 0
fi
LIST=""
for c in §PID §(ps -A -o PID,PPID 2>/dev/null | while read a b; do [ "§b" = "§PID" ] && echo §a; done); do
  r=§(readlink -f "/proc/§c/root" 2>/dev/null)
  if [ "§r" = "§CANON" ]; then LIST="§LIST §c"; fi
done
if [ -z "§LIST" ]; then
  rm -f "§RUN/guest.pid" "§RUN/guest.started"
  echo "stopped=none"
  echo "leaked_mounts=§(grep -c " §CANON/" /proc/self/mountinfo 2>/dev/null)"
  exit 0
fi
kill §LIST 2>/dev/null
i=0
ALIVE=""
while [ §i -lt 5 ]; do
  sleep 1
  ALIVE=""
  for c in §LIST; do [ -d "/proc/§c" ] && ALIVE="§ALIVE §c"; done
  [ -z "§ALIVE" ] && break
  i=§((i+1))
done
if [ -n "§ALIVE" ]; then kill -9 §ALIVE 2>/dev/null; sleep 1; fi
if [ -d "/proc/§PID" ] && grep -q unshare "/proc/§PID/cmdline" 2>/dev/null; then kill -9 §PID 2>/dev/null; fi
rm -f "§RUN/guest.pid" "§RUN/guest.started"
echo "stopped=ok"
echo "leaked_mounts=§(grep -c " §CANON/" /proc/self/mountinfo 2>/dev/null)"
""".trimStart()

    private val STATUS = """
#!/system/bin/sh
ROOT=@ROOT@
RUN=@RUN@
CANON=§(readlink -f "§ROOT")
PID=§(cat "§RUN/guest.pid" 2>/dev/null)
echo "uid=§(id -u)"
FOUND=""
if [ -n "§PID" ]; then
  for c in §PID §(ps -A -o PID,PPID 2>/dev/null | while read a b; do [ "§b" = "§PID" ] && echo §a; done); do
    r=§(readlink -f "/proc/§c/root" 2>/dev/null)
    if [ "§r" = "§CANON" ]; then FOUND="§FOUND §c"; fi
  done
fi
set -- §FOUND
echo "procs=§#"
echo "pid=§{1:-}"
if [ -f "§RUN/guest.started" ]; then echo "started=§(cat "§RUN/guest.started")"; fi
echo "now=§(date +%s)"
""".trimStart()

    /** Разбор вывода status.sh. */
    fun parseStatus(out: String): ContainerStatus {
        val m = keyValues(out)
        val procs = m["procs"]?.toIntOrNull() ?: 0
        val started = m["started"]?.toLongOrNull()
        val now = m["now"]?.toLongOrNull()
        return ContainerStatus(
            running = procs > 0, pid = m["pid"]?.toIntOrNull(), processes = procs,
            uptimeSec = if (procs > 0 && started != null && now != null) (now - started).coerceAtLeast(0) else null,
        )
    }

    data class StopResult(val stopped: Boolean, val leakedMounts: Int)

    fun parseStop(out: String): StopResult {
        val m = keyValues(out)
        return StopResult(m["stopped"] in setOf("ok", "none", "nopid"), m["leaked_mounts"]?.toIntOrNull() ?: 0)
    }

    private fun keyValues(out: String) =
        out.lines().mapNotNull { l -> l.split('=', limit = 2).takeIf { it.size == 2 }?.let { it[0].trim() to it[1].trim() } }.toMap()
}
